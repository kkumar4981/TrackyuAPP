    } catch (_) {
      if (acceptedReceipt != null && punchActor == employeeId &&
          punchToken == api.dio.options.headers['Authorization']) {
        attendance = acceptedReceipt;
        notice = 'Attendance confirmed by server. Local cache needs retry.';
        await _cache();
        return;
      }
      rethrow;
    }
  }

  Future<bool> restoreDataFromServer() async {































    if (restoring) return false;































    restoring = true;































    final workspace = local, revision = _workspaceRevision;































    final owner = employeeId, baseUrl = api.baseUrl;































    bool same() =>































        !_disposed &&































        revision == _workspaceRevision &&































        identical(workspace, local) &&































        owner == employeeId &&































        baseUrl == api.baseUrl;































    void ensure() {































      if (!same()) {































        throw const ApiFailure(































          'SESSION_CHANGED',































          'Workspace changed during restore.',































        );































      }































    }































































    var restored = 0;































    final failures = <String>[];































    try {































      if (workspace == null) {































        await refresh();































        ensure();































        notice = 'Workspace refreshed. Daily restore requires phone storage.';































        return false;































      }































      final state = await workspace.syncState();































      ensure();































      if ((state['pending'] as num? ?? 0) + (state['blocked'] as num? ?? 0) >































          0) {































        notice = 'Sync pending phone activities before restoring server data.';































        return false;































      }































      try {































        final value = await api.request('Portal/profile');































        ensure();































        if (value is Map) {































          final profile = Map<String, dynamic>.from(value);































          await workspace.write('response:Portal/profile:null', {































            'value': profile,































          });































          ensure();































          if (profile.containsKey('mode') || profile.containsKey('isField')) {































            isField = profile['mode'] == 'Field' || profile['isField'] == true;































          }































          if (profile['offices'] is List) offices = rowsOf(profile['offices']);































          if (!isField) {































            final office = offices































                .where((o) => o['isEnabled'] == true && o['isMember'] == true)































                .firstOrNull;































            officeId = (office?['id'] as num?)?.toInt();































          }































        }































      } catch (e, stack) {































        ensure();































        failures.add('profile');































        await ErrorLogger.record(e, stack, context: 'restore.profile');































      }































      final today = DateTime.parse(localDay);































      // Two concurrent downloads, separate date keys; never guess a date for the legacy day: record.































      var next = 0;































      Future<void> worker() async {































        while (next < 7) {































          ensure();































          final offset = next++;































          final day = LocalWorkspace.day(































            today.subtract(Duration(days: offset)),































          );































          try {































            final response = await api.request(































              'DutyTracking/day',































              body: {'date': day, 'includeRaw': true},































            );































            ensure();































            if (response is! Map) {































              throw const FormatException('Invalid daily report response');































            }































            final report = Map<String, dynamic>.from(response);































            if (!rowBelongs(report, owner, baseUrl) ||































                report['date'] != null &&































                    '${report['date']}'.substring(0, 10) != day) {































              throw const FormatException('Daily report owner/date mismatch');































            }































            final visitsResponse = await api.request(































              'MobileVisits/mine?date=$day',































            );































            ensure();































            if (visitsResponse is! List &&































                !(visitsResponse is Map && visitsResponse['rows'] is List)) {































              throw const FormatException('Invalid visit response');































            }































            final previous = await workspace.read('day:$day') ?? {};































            ensure();































            final old = previous['report'] is Map































                ? Map<String, dynamic>.from(previous['report'])































                : <String, dynamic>{};































            final visits = reconcileVisits(































              [































                ...rowsOf(old['visits']),































                ...rowsOf(report['visits'] ?? report['Visits']),































                ...rowsOf(visitsResponse),































                ...rowsOf(previous['visits']),































              ],































              [],































              day,































              owner,































              baseUrl,































            );































            final localAtt = previous['attendance'] is Map































                ? Map<String, dynamic>.from(previous['attendance'])































                : null;































            final serverAtt = rowsOf(report['attendance'])































                .where(































                  (r) =>































                      businessDay(































                        instant(r['punchInUtc'] ?? r['PunchInUtc']) ?? DateTime.utc(1970),































                      ) ==































                      day,































                )































                .firstOrNull;































            final attendance = reconcileAttendance(serverAtt, localAtt);































            final mergedReport = <String, dynamic>{































              ...old,































              ...report,































              'recordedPoints': mergePoints(































                [































                  ...rowsOf(old['recordedPoints']),































                  ...rowsOf(report['recordedPoints']),































                ],































                day,































                owner,































                baseUrl,































              ),































              'events': dayEvents([































                ...rowsOf(old['events']),































                ...rowsOf(report['events']),































                ...attendanceEvents([if (attendance != null) attendance], day),































              ], day),































              'visits': visits,































            };































            ensure();































            await workspace.write('day:$day', {































              ...previous,































              'report': mergedReport,































              'visits': visits,































              if (attendance != null) 'attendance': attendance,































            });































            ensure();































            restored++;































          } catch (e, stack) {































            ensure();































            failures.add(day);































            await ErrorLogger.record(e, stack, context: 'restore.day');































          }































        }































      }































































      await Future.wait([worker(), worker()]);































      ensure();































      final range = <String, dynamic>{































        'fromDate': LocalWorkspace.day(































          today.subtract(const Duration(days: 30)),































        ),































        'toDate': localDay,































        'page': 1,































        'pageSize': 100,































      };































      for (final route in [































        'OfficeLeave/mine',































        'OfficeReminders/mine',































        'OfficePreIntimation/personal',































      ]) {































        ensure();































        try {































          final response = await api.request(































            route,































            body: route.endsWith('/personal') ? range : null,































          );































          ensure();































          if (response is! List) {































            throw const FormatException('Invalid request history response');































          }































          await workspace.write('collection:$route:', {'rows': response});































          ensure();































        } catch (e, stack) {































          ensure();































          failures.add(route);































          await ErrorLogger.record(e, stack, context: 'restore.requests');































        }































      }































      for (final office in offices.where(































        (o) => o['isMember'] == true && o['isEnabled'] == true,































      )) {































        ensure();































        final rows = <dynamic>[];































        var complete = false;































        try {































          for (var page = 1; page <= 100; page++) {































            final response = await api.request(































              'OfficeActivities/mine',































              body: {...range, 'officeId': office['id'], 'page': page},































            );































            ensure();































            if (response is! List) {































              throw const FormatException('Invalid activities response');































            }































            rows.addAll(response);































            if (response.length < 100) {































              complete = true;































              break;































            }































          }































          if (!complete) {































            throw const FormatException(































              'Activity history exceeds restore limit',































            );































          }































          await workspace.write(































            'collection:OfficeActivities/mine:${office['id']}',































            {'rows': rows},































          );































          ensure();































        } catch (e, stack) {































          ensure();































          failures.add('activities');































          await ErrorLogger.record(e, stack, context: 'restore.activities');































        }































      }































      await readLocal();































      ensure();































      restoreOffered = false;































      notice = failures.isEmpty































          ? '$restored daily timelines restored. Request/activity history covers the last 31 days.'































          : 'Restored $restored of 7 daily timelines; ${failures.length} downloads failed. Phone records are retained. Retry restore.';































      return failures.isEmpty && restored == 7;































    } catch (e, stack) {































      await ErrorLogger.record(e, stack, context: 'restore.interrupted');































      if (same()) {































        notice =































            'Restore interrupted. Downloaded days are retained; retry restore.';































      }































      return false;































    } finally {































      restoring = false;































      notifyListeners();































    }































  }































}































