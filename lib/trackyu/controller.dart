  Future<bool> reconcileServerWorkspace() {
    final scope = '$visitCacheScope|${api.dio.options.headers['Authorization']}';
    if (_serverSnapshot != null && _serverSnapshotScope == scope) return _serverSnapshot!;
    _serverSnapshotScope = scope;
    final task = _pullServerWorkspace();
    _serverSnapshot = task;
    return task.whenComplete(() {
      if (identical(_serverSnapshot, task)) _serverSnapshot = null;
    });
  }

  Future<bool> _pullServerWorkspace() async {
    final workspace = local, revision = _workspaceRevision, activity = _activityRevision;
    final scope = visitCacheScope, token = api.dio.options.headers['Authorization'];
    final date = localDay, field = isField, office = officeId;
    if (user == null || (!field && office == null)) return false;
    bool current() => !_disposed && revision == _workspaceRevision &&
        activity == _activityRevision && scope == visitCacheScope && date == localDay &&
        token == api.dio.options.headers['Authorization'] && identical(workspace, local);
    late List<dynamic> result;
    try {
      result = await Future.wait<dynamic>([
        field ? api.fieldState() : api.state(office!),
        api.request('MobileVisits/mine?date=$date'),
      ]);
    } catch (_) {
      if (!current()) return false;
      rethrow;
    }
    if (!current()) return false;
    if (result[0] is! Map) throw const ApiFailure('INVALID_ATTENDANCE_SNAPSHOT', 'Attendance refresh was incomplete. Saved activity is retained.');
    final state = Map<String, dynamic>.from(result[0] as Map);
    if (result[1] is! List) throw const ApiFailure('INVALID_VISIT_SNAPSHOT', 'Visit refresh was incomplete. Saved activity is retained.');
    final remote = rowsOf(result[1]).map(normalizeVisit).toList();
    final day = workspace == null ? <String, dynamic>{} : await localDayData(date);
    if (!current()) return false;
    final cached = workspace == null ? await scopedVisitCache() : rowsOf(day['visits']);
    if (!current()) return false;
    final legacyVisits = cached.where(unconfirmedRegularVisit).toList();
    final visits = mergePendingVisits(remote, cached.where((r) => !unconfirmedRegularVisit(r)).toList());
    final localAtt = day['attendance'] is Map
        ? normalizeAttendance(Map<String, dynamic>.from(day['attendance'])) : attendance;
    final rawAtt = state['attendance'] ?? state['Attendance'];
    final serverAtt = rawAtt is Map ? normalizeAttendance(Map<String, dynamic>.from(rawAtt)) : null;
    final pending = localAtt?['syncState'] == 'pending' || localAtt?['syncState'] == 'blocked';
    final mergedAtt = serverAtt;
    if (workspace != null) {
      await workspace.write('day:$date', {...day, if (pending) 'legacyAttendanceForReview': localAtt, if (legacyVisits.isNotEmpty) 'legacyRegularVisitsForReview': [...rowsOf(day['legacyRegularVisitsForReview']), ...legacyVisits], 'attendance': mergedAtt, 'visits': visits});
    }
    if (!current()) return false;
    attendance = mergedAtt;
    workDate = '${state['workDate'] ?? state['WorkDate'] ?? date}';
    syncServerTime(state['serverTimeUtc'] ?? state['ServerTimeUtc']);
    stateKnown = true;
    offline = false;
    for (final row in remote.where(visitClosed)) { markVisitClosedInMemory(row); }
    await saveVisitCacheRows(visits);
    if (!current()) return false;
    activeVisit = onDuty ? visits.where((r) => !isVisitClosedOrClosing(r)).firstOrNull : null;
    await _cache();
    notifyListeners();
    return true;
  }

