int compareVersions(String a, String b) {







  final cleanA = a.replaceAll(RegExp(r'^[vV]'), '').trim();







  final cleanB = b.replaceAll(RegExp(r'^[vV]'), '').trim();







  final pa = cleanA.split('.').map((s) => int.tryParse(s) ?? 0).toList();







  final pb = cleanB.split('.').map((s) => int.tryParse(s) ?? 0).toList();







  final len = pa.length > pb.length ? pa.length : pb.length;







  for (var i = 0; i < len; i++) {







    final na = i < pa.length ? pa[i] : 0;







    final nb = i < pb.length ? pb[i] : 0;







    if (na != nb) return na.compareTo(nb);







  }







  return 0;







}















