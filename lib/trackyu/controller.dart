  Future<Json> _quickFallbackLocation() async {

    final now = DateTime.now().toUtc();

    try {

      final last = await Geolocator.getLastKnownPosition();

      if (last != null) {

        final fixTime = last.timestamp.toUtc();

        if (isValidGpsFix(

          lat: last.latitude,

          lng: last.longitude,

          acc: last.accuracy,

          capturedAt: fixTime,

          isMocked: last.isMocked,

          now: now,

        )) {

          return {

            'latitude': last.latitude,

            'longitude': last.longitude,

            'accuracy': last.accuracy,

            'accuracyMeters': last.accuracy,

            'capturedAtUtc': fixTime.toIso8601String(),

          };

        }

      }

    } catch (_) {}



    final lastKnown = lastLocation;

    if (lastKnown != null) {

      final lat = (lastKnown['latitude'] as num?)?.toDouble();

      final lng = (lastKnown['longitude'] as num?)?.toDouble();

      final acc = (lastKnown['accuracyMeters'] as num?)?.toDouble()

          ?? (lastKnown['accuracy'] as num?)?.toDouble();

      final capturedStr = lastKnown['capturedAtUtc'] as String?;

      final fixTime = capturedStr != null ? DateTime.tryParse(capturedStr)?.toUtc() : null;

      final isMock = (lastKnown['isMocked'] as bool?) ?? false;



      if (isValidGpsFix(

        lat: lat,

        lng: lng,

        acc: acc,

        capturedAt: fixTime,

        isMocked: isMock,

        now: now,

      )) {

        return {

          'latitude': lat!,

          'longitude': lng!,

          'accuracy': acc!,

          'accuracyMeters': acc,

          'capturedAtUtc': fixTime!.toIso8601String(),

        };

      }

    }



    throw Exception('Fresh GPS location unavailable for punch-out. Please acquire an active GPS fix.');

  }



