          ? await api.fieldPunch(out, payload)







          : await api.punch(out, payload);







      final saved = normalizeAttendance(savedRaw);
      if ((int.tryParse('${saved['id']}') ?? 0) <= 0 || saved['punchInUtc'] == null ||
          (out && saved['punchOutUtc'] == null)) {
        throw const ApiFailure('INVALID_PUNCH_RECEIPT',
            'Server confirmation was incomplete. Refresh attendance before retrying.');
      }
      if (out && int.tryParse('${saved['id']}') != attId) {
        throw const ApiFailure('INVALID_PUNCH_RECEIPT', 'Server acknowledgement belongs to a different attendance. Refresh before retrying.');
      }
      if (_disposed || punchActor != employeeId ||
          punchToken != api.dio.options.headers['Authorization']) {
        throw const ApiFailure('SESSION_CHANGED', 'Account changed. Attendance remains with the original account.');
      }
      acceptedReceipt = saved;
      _activityRevision++;








      if (out) await DutyTracker.stop();







      attendance = saved;







      if (local != null) {







        final current = await localDayData();







        await local!.write(dayKey, {







          ...current,







          'attendance': saved,







        });







      }







      syncServerTime(saved['serverTimeUtc']);































      stateKnown = true;































      notice = out































          ? 'Punch-out confirmed by server.'































          : 'Punch-in confirmed by server.';































      offline = false;































      await _tracking();































      await _cache();































      final telemetry = location['telemetry'];































      if (telemetry is Map) {































        final missing = [































          if (telemetry['batteryPercent'] == null) 'battery',































