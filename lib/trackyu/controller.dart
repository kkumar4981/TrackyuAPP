  bool _syncingVisitQueue = false;

  Future<void> syncPendingVisits() async {
    if (_syncingVisitQueue || pendingVisits.isEmpty) return;
    _syncingVisitQueue = true;
    final syncScope = '${api.baseUrl}|$employeeId';
    final syncUser = user;
    final syncWorkspace = local;
    bool currentSession() => identical(user, syncUser) &&
        identical(local, syncWorkspace) &&
        '${api.baseUrl}|$employeeId' == syncScope;
    try {
      final queue = List<Map<String, dynamic>>.from(pendingVisits);
      for (final item in queue) {
        if (!currentSession()) return;
        if (item['scope'] != syncScope) continue;
        try {
          final legacyBody = item['body'] is Map ? Map<String, dynamic>.from(item['body']) : <String, dynamic>{};
          if ('${legacyBody['kind'] ?? ''}'.trim().toLowerCase() == 'regular' || legacyBody['retailerId'] != null) {
            lastSyncError = 'Earlier offline regular visit retained for review; direct server confirmation is required.';
            continue;
          }
          if(item['durable']==false)await _preservePendingVisits();
          if(!currentSession())return;
          final finish = item['finish'] == true;
          final body = Map<String, dynamic>.from(item['body'] as Map);
          final receipt = await api.request(
            'MobileVisits/${finish ? "finish" : "start"}', body: body);
          if (!currentSession()) return;
          final id = receipt is Map ? int.tryParse('${receipt['id']}') : null;
          final expectedId = int.tryParse('${body['id']}');
          if (id == null || id <= 0 ||
              (finish && expectedId != null && expectedId > 0 && id != expectedId)) {
            throw const ApiFailure('INVALID_VISIT_RECEIPT',
                'Checkout acknowledgement could not be verified. Saved data is retained.');
          }
          // Only acknowledge the exact operation, never another employee/day's
          // queue entry sharing the same numeric visit ID.
          if(finish)await persistVisitClose({...body,...Map<String,dynamic>.from(receipt as Map),'id':id,'serverId':id,'requestId':body['startRequestId'],'checkoutAcknowledged':true,'syncState':'synced','isOffline':false});
          if(!currentSession())return;
          pendingVisits.removeWhere((p) => identical(p, item));
          await _preservePendingVisits();
          if (!currentSession()) return;
          notifyListeners();
        } catch (e) {
          if (!currentSession()) return;
          // HTTP errors are not receipts: validation/conflict/auth failures must
          // not silently discard the checkout or its departure photo.
          lastSyncError = e is ApiFailure
              ? 'Visit sync pending (${e.code}). Saved checkout is retained.'
              : 'Visit sync pending. Saved checkout is retained.';
          await _preservePendingVisits();
          if (currentSession()) notifyListeners();
          break;
        }
      }
    } finally {
      _syncingVisitQueue = false;
    }
  }

