  Future<dynamic> workspaceRequest(String route, {Json? body}) async {































    if (local == null) return api.request(route, body: body);































    const personalReads = {































      'OfficeLeave/mine',































      'OfficeActivities/mine',































      'OfficeReminders/mine',































      'OfficePreIntimation/personal',































    };































    if (personalReads.contains(route)) {































      final collection = await local!.read(































        'collection:$route:${body?['officeId'] ?? ''}',































      );































      if (collection != null) {































        var rows = (collection['rows'] as List? ?? [])































            .map((r) => Map<String, dynamic>.from(r))































            .where((r) {































              final date = '${r['activityDate'] ?? r['workDate'] ?? ''}'































                  .split('T')































                  .first;































              return date.isEmpty ||































                  body == null ||































                  (date.compareTo('${body['fromDate']}') >= 0 &&































                      date.compareTo('${body['toDate']}') <= 0);































            })































            .toList();































        if (body != null) {































          rows = rows































              .skip(































                (((body['page'] as num?)?.toInt() ?? 1) - 1) *































                    ((body['pageSize'] as num?)?.toInt() ?? 50),































              )































              .take((body['pageSize'] as num?)?.toInt() ?? 50)































              .toList();































        }































        return rows;































      }































    }































    if (route == 'Portal/attendance' || route == 'Portal/team-attendance') {
      final fromStr = '${body?['fromDate'] ?? ''}';
      final toStr = '${body?['toDate'] ?? ''}';
      final isSingleHistoricalDay = fromStr.isNotEmpty &&
          fromStr == toStr &&
          fromStr != localDay;

      // When online and viewing a date range or today, fetch complete records from server
      if (!offline && !isSingleHistoricalDay) {
        try {
          final serverRes = await api.request(route, body: body);
          if (serverRes is Map && serverRes['rows'] is List) {
            final serverRows = (serverRes['rows'] as List)
                .whereType<Map>()
                .map((r) => Map<String, dynamic>.from(r))
                .toList();
            // Also merge today's local attendance if present, in range, and not in serverRows
            final todayStr = localDay;
            final todayDate = DateTime.tryParse(todayStr);
            final fromDate = DateTime.tryParse(fromStr);
            final toDate = DateTime.tryParse(toStr);
            final isTodayInRange = todayDate != null &&
                (fromDate == null || !todayDate.isBefore(fromDate)) &&
                (toDate == null || !todayDate.isAfter(toDate));

            if (isTodayInRange) {
              final todayDay = await localDayData(todayStr);
              if (todayDay['attendance'] is Map) {
                final hasToday = serverRows.any(
                  (r) => '${r['workDate']}'.startsWith(todayStr),
                );
                if (!hasToday) {
                  serverRows.insert(0, {
                    ...Map<String, dynamic>.from(todayDay['attendance'] as Map),
                    'mode':
                        (todayDay['attendance'] as Map)['mode'] ??
                        (isField ? 'Field' : 'Office'),
                    'workDate': todayStr,
                  });
                }
              }
            }
            return {'rows': serverRows};
          }
        } catch (_) {}
      }

      // Offline mode or single historical day: read from local workspace storage
      final from = DateTime.tryParse(fromStr) ?? DateTime.now();
      final to = DateTime.tryParse(toStr) ?? from;
      final records = <Json>[];
      for (
        var date = from;
        !date.isAfter(to);
        date = date.add(const Duration(days: 1))
      ) {
        final day = await localDayData(LocalWorkspace.day(date));
        if (day['attendance'] is Map) {
          records.add({
            ...Map<String, dynamic>.from(day['attendance']),
            'mode':
                (day['attendance'] as Map)['mode'] ??
                (isField ? 'Field' : 'Office'),
            'workDate': LocalWorkspace.day(date),
          });
        }
      }
      if (records.isNotEmpty) {
        return {'rows': records.reversed.toList()};
      }
      if (!offline) {
        try {
          final serverRes = await api.request(route, body: body);
          if (serverRes is Map && serverRes['rows'] is List) {
            final serverRows = (serverRes['rows'] as List)
                .whereType<Map>()
                .map((r) => Map<String, dynamic>.from(r))
                .toList();
            return {'rows': serverRows};
          }
        } catch (_) {}
      }
      return {'rows': records.reversed.toList()};
    }

    const writes = {































      'OfficeLeave/apply',































      'OfficeActivities/save',































      'OfficeReminders/save',































      'OfficePreIntimation/submit',































    };































    if (body != null && writes.contains(route)) {































      final id = const Uuid().v4();































      final day = await localDayData();































      final activities = List<dynamic>.from(day['activities'] as List? ?? []);































      activities.add({































        'operationId': id,































        'route': route,































        'body': body,































        'atUtc': DateTime.now().toUtc().toIso8601String(),































        'syncState': 'pending',































      });































      await commitLocal(































        {...day, 'activities': activities},































        {'id': id, 'route': route, 'body': body},































      );































      return {'id': id, 'savedOnPhone': true};































    }































    final key = 'response:$route:${jsonEncode(body)}';































    final cached = await local!.read(key);































    if (cached != null) return cached['value'];































    if (offline) {































      if (route == 'Portal/profile') return {'offices': offices};































      if (route.contains('attendance') || route == 'Portal/visits') {































        return {'rows': [], 'regular': [], 'open': []};































      }































      return <Json>[];































    }































    final value = await api.request(route, body: body);































    await local!.write(key, {'value': value});































    return value;































  }































































