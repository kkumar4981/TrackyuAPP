Map<String, dynamic> normalizeAttendance(Map<String, dynamic> map) {







  final out = Map<String, dynamic>.from(map);







  if (out['punchInUtc'] == null && out['PunchInUtc'] != null) out['punchInUtc'] = out['PunchInUtc'];







  if (out['punchOutUtc'] == null && out['PunchOutUtc'] != null) out['punchOutUtc'] = out['PunchOutUtc'];







  if (out['id'] == null && out['Id'] != null) out['id'] = out['Id'];







  if (out['workDate'] == null && out['WorkDate'] != null) out['workDate'] = out['WorkDate'];







  if (out['hasSelfie'] == null && out['HasSelfie'] != null) out['hasSelfie'] = out['HasSelfie'];







  if (out['hasOutSelfie'] == null && out['HasOutSelfie'] != null) out['hasOutSelfie'] = out['HasOutSelfie'];







  return out;







}















